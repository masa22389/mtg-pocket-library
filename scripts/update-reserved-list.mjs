#!/usr/bin/env node

// Builds reserved-list.js: every card on the Reserved List (Scryfall is:reserved) as [oracle ID, English name].
// The list does not grow, so the app carries it and marks owned cards without changing saved lots.
// Run: node scripts/update-reserved-list.mjs, then node scripts/update-asset-hashes.mjs.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const headers = { "User-Agent": "mtg-pocket-library/1.0", Accept: "application/json" };

const cards = new Map();
let url = "https://api.scryfall.com/cards/search?q=is%3Areserved&unique=cards&order=name";
while (url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`Scryfall ${response.status}`);
  const page = await response.json();
  for (const card of page.data) if (card.reserved && card.oracle_id) cards.set(card.oracle_id, card.name);
  url = page.has_more ? page.next_page : "";
  if (url) await new Promise(resolve => setTimeout(resolve, 120));
}
if (cards.size < 500) throw new Error(`only ${cards.size} reserved cards; refusing to write`);
const rows = [...cards].sort((a, b) => a[1].localeCompare(b[1]));
const text = `// Generated by scripts/update-reserved-list.mjs from Scryfall is:reserved. [oracle ID, English name]\n`
  + `window.MTG_RESERVED_LIST = [\n${rows.map(row => `  ${JSON.stringify(row)}`).join(",\n")}\n];\n`;
await writeFile(path.join(PROJECT_DIR, "reserved-list.js"), text);
console.log(`reserved-list.js: ${rows.length} cards`);
